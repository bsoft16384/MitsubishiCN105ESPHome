TEST(RealConnect, PacketMatchesCapture) {
    EXPECT_EQ(CONNECT[0], 0xFC);
    EXPECT_EQ(CONNECT[1], 0x5A);
    EXPECT_EQ(CONNECT[5], 0xCA);
    EXPECT_EQ(CONNECT[7], 0xA8);
    EXPECT_EQ(checksum(CONNECT, 7), 0xA8);
}
